#!/usr/bin/env bash
# Reproducible walkthrough: build the demo repo, preview heal, apply heal.
# Usage:
#   ./scripts/demo.sh              # run on stdout (temp repo)
#   ./scripts/demo.sh --refresh    # update examples/demo-project/heal-output.txt + demo-transcript.txt
#   ./scripts/demo.sh --vhs        # record docs/demo.gif when `vhs` is installed (offline)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CLI="${GITBRAIN_CLI:-$ROOT/dist/cli.js}"
BUILD="${ROOT}/examples/demo-project/build-history.sh"
EXAMPLE="${ROOT}/examples/demo-project"
HEAL_OUTPUT="${EXAMPLE}/heal-output.txt"
TRANSCRIPT="${EXAMPLE}/demo-transcript.txt"
TAPE="${ROOT}/scripts/demo.tape"
DEMO_GIF="${ROOT}/docs/demo.gif"
HEAL_NOW="${GITBRAIN_DEMO_HEAL_DATE:-2026-10-22T12:00:00.000Z}"

usage() {
  cat <<EOF
Usage: $0 [--refresh] [--vhs]

  (default)  Build a temp demo repo and run brain heal (dry-run, then apply).
  --refresh  Regenerate committed heal-output.txt and demo-transcript.txt (stable heal date).
  --vhs      Record ${DEMO_GIF} via Charm VHS when \`vhs\` is on PATH (no network).

Requires: npm run build (dist/cli.js) before running.
EOF
}

require_cli() {
  if [[ ! -f "$CLI" ]]; then
    echo "missing CLI at $CLI — run npm run build in the gitbrain repo first" >&2
    exit 1
  fi
}

run_heal_formatted() {
  local dir="$1"
  local dry_flag="${2:-0}"
  GITBRAIN_DEMO_DIR="$dir" GITBRAIN_DEMO_DRY="$dry_flag" node --input-type=module <<NODE
import { runHeal, formatHealHumanOutput } from "${ROOT}/dist/commands/heal.js";
const projectDir = process.env.GITBRAIN_DEMO_DIR;
if (!projectDir) throw new Error("GITBRAIN_DEMO_DIR");
const result = runHeal(projectDir, {
  dryRun: process.env.GITBRAIN_DEMO_DRY === "1",
  now: new Date("${HEAL_NOW}"),
});
process.stdout.write(formatHealHumanOutput(result));
NODE
}

append_transcript() {
  local line="$1"
  printf '%s\n' "$line" >>"$TRANSCRIPT_BUF"
}

run_demo_session() {
  local dir="$1"
  local capture="${2:-0}"

  if [[ "$capture" == "1" ]]; then
    : >"$TRANSCRIPT_BUF"
    append_transcript '# gitbrain demo transcript (generated by scripts/demo.sh --refresh)'
    append_transcript ''
  fi

  local cmd_build="./examples/demo-project/build-history.sh \"\$DIR\""
  if [[ "$capture" == "1" ]]; then
    append_transcript "\$ DIR=\$(mktemp -d)"
    append_transcript "\$ $cmd_build"
  else
    echo "\$ DIR=\$(mktemp -d)"
    echo "\$ $cmd_build"
  fi
  bash "$BUILD" "$dir"

  local dry_cmd="node dist/cli.js heal --dry-run \"\$DIR\""
  if [[ "$capture" == "1" ]]; then
    append_transcript "\$ $dry_cmd"
    append_transcript ''
    run_heal_formatted "$dir" 1 >>"$TRANSCRIPT_BUF"
    append_transcript ''
    append_transcript "\$ node dist/cli.js heal \"\$DIR\""
    append_transcript ''
    local apply_out
    apply_out="$(run_heal_formatted "$dir" 0)"
    printf '%s' "$apply_out" >>"$TRANSCRIPT_BUF"
    printf '%s' "$apply_out" >"$HEAL_OUTPUT"
  else
    echo ""
    echo "\$ $dry_cmd"
    echo ""
    run_heal_formatted "$dir" 1
    echo ""
    echo "\$ node dist/cli.js heal \"\$DIR\""
    echo ""
    run_heal_formatted "$dir" 0
  fi
}

do_refresh() {
  require_cli
  local dir transcript_buf
  dir="$(mktemp -d "${TMPDIR:-/tmp}/gitbrain-demo.XXXXXX")"
  transcript_buf="$(mktemp)"
  TRANSCRIPT_BUF="$transcript_buf"

  run_demo_session "$dir" 1
  mv "$TRANSCRIPT_BUF" "$TRANSCRIPT"
  rm -rf "$dir" "$transcript_buf"
  echo "Updated $HEAL_OUTPUT and $TRANSCRIPT"
}

do_vhs() {
  if ! command -v vhs >/dev/null 2>&1; then
    echo "vhs not found — install from https://github.com/charmbracelet/vhs or run without --vhs" >&2
    exit 1
  fi
  require_cli
  if [[ ! -f "$TAPE" ]]; then
    echo "missing tape: $TAPE" >&2
    exit 1
  fi
  GITBRAIN_ROOT="$ROOT" vhs record "$TAPE"
  echo "Wrote $DEMO_GIF"
}

main() {
  local mode=run
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --refresh) mode=refresh ;;
      --vhs) mode=vhs ;;
      -h | --help)
        usage
        exit 0
        ;;
      *)
        echo "unknown argument: $1" >&2
        usage >&2
        exit 1
        ;;
    esac
    shift
  done

  case "$mode" in
    refresh) do_refresh ;;
    vhs) do_vhs ;;
    run)
      require_cli
      local demo_dir
      demo_dir="$(mktemp -d "${TMPDIR:-/tmp}/gitbrain-demo.XXXXXX")"
      run_demo_session "$demo_dir" 0
      rm -rf "$demo_dir"
      ;;
  esac
}

main "$@"
